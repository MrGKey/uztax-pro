export function ChartSparkline() {
  const points = [40, 55, 48, 72, 65, 80, 75, 90, 85, 95, 88, 110];
  const max = Math.max(...points);
  const w = 200; const h = 40;
  const cx = (i: number) => (i / (points.length - 1)) * w;
  const cy = (v: number) => h - (v / max) * h;
  const d = points.map((v, i) => `${i === 0 ? 'M' : 'L'}${cx(i)},${cy(v)}`).join(' ');
  const fillD = `${d} L${w},${h} L0,${h} Z`;

  return (
    <svg width={w} height={h} viewBox={`0 0 ${w} ${h}`} style={{ width: '100%', height: 40 }}>
      <defs>
        <linearGradient id="sparkFill" x1="0" y1="0" x2="0" y2="1">
          <stop offset="0%" stopColor="var(--primary)" stopOpacity="0.3" />
          <stop offset="100%" stopColor="var(--primary)" stopOpacity="0" />
        </linearGradient>
      </defs>
      <path d={fillD} fill="url(#sparkFill)" />
      <path d={d} fill="none" stroke="var(--primary)" strokeWidth="2" strokeLinecap="round" />
    </svg>
  );
}
